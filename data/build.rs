use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    generate_bundled_source_manifest().unwrap_or_else(|error| panic!("{error}"));
}

fn collect_sources(
    dir: &Path,
    rel_include_prefix: &str,
    sources: &mut Vec<(String, String, PathBuf)>,
) -> Result<(), String> {
    if !dir.exists() {
        return Ok(());
    }
    println!("cargo:rerun-if-changed={}", dir.display());

    let entries = fs::read_dir(dir).map_err(|error| {
        format!(
            "{}: could not read indicator directory: {error}",
            dir.display()
        )
    })?;

    for entry in entries {
        let entry = entry.map_err(|error| {
            format!(
                "{}: could not inspect indicator entry: {error}",
                dir.display()
            )
        })?;
        let path = entry.path();
        if path.is_file() && path.extension().and_then(|ext| ext.to_str()) == Some("ind") {
            let file_name = path
                .file_name()
                .and_then(|name| name.to_str())
                .ok_or_else(|| format!("{}: invalid UTF-8 filename", path.display()))?
                .to_owned();
            let include_path = format!("{rel_include_prefix}/{file_name}");
            println!("cargo:rerun-if-changed={}", path.display());
            sources.push((file_name, include_path, path));
        }
    }
    Ok(())
}

fn generate_bundled_source_manifest() -> Result<(), String> {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let mut source_files = Vec::new();

    // 1. Core indicators from data/indicators/sources
    let core_dir = manifest_dir.join("indicators/sources");
    collect_sources(&core_dir, "/indicators/sources", &mut source_files)?;

    // 2. Catalog indicators from workspace root indicators/sources
    let catalog_dir = manifest_dir.join("../indicators/sources");
    collect_sources(&catalog_dir, "/../indicators/sources", &mut source_files)?;

    source_files.sort_by(|a, b| a.0.cmp(&b.0));

    if source_files.is_empty() {
        return Err(format!(
            "{} and {} contain no bundled indicator .ind sources",
            core_dir.display(),
            catalog_dir.display()
        ));
    }

    let out_dir = env::var_os("OUT_DIR").expect("Cargo OUT_DIR missing");
    let destination = PathBuf::from(out_dir).join("indicator_bundled_sources.rs");
    let mut generated = String::from(
        "// Generated by data/build.rs; edit source files under indicators/sources instead.\n\nconst BUNDLED_SOURCES: &[BundledSource] = &[\n",
    );

    for (file_name, include_path, _) in source_files {
        generated.push_str(&format!(
            "    BundledSource {{\n        file_name: {file_name:?},\n        source: include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {include_path:?})),\n    }},\n"
        ));
    }

    generated.push_str("];\n");
    fs::write(&destination, generated).map_err(|error| {
        format!(
            "could not generate bundled indicator source manifest {}: {error}",
            destination.display()
        )
    })
}
